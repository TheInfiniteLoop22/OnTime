"""Data-quality report for the raw tables, generated from code (never hand-typed).

Why: BUILD_PLAN Phase 1 requires row counts, null %, duplicate keys, out-of-range values and
geolocation outliers, with every number traceable to this module.
"""

from __future__ import annotations

import logging

import pandas as pd

from ontime.config import load_config, project_path

log = logging.getLogger(__name__)

# Natural key per table (None = no single key, rows are line items / points).
KEYS: dict[str, list[str] | None] = {
    "orders": ["order_id"],
    "order_items": ["order_id", "order_item_id"],
    "products": ["product_id"],
    "sellers": ["seller_id"],
    "customers": ["customer_id"],
    "geolocation": None,
    "payments": ["order_id", "payment_sequential"],
    "reviews": ["review_id"],
    "category_translation": ["product_category_name"],
}

SECTION_START = "<!-- raw-quality:start -->"
SECTION_END = "<!-- raw-quality:end -->"


def row_counts(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    return pd.DataFrame(
        [{"table": n, "rows": len(df), "columns": df.shape[1]} for n, df in tables.items()]
    )


def null_percentages(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Columns with at least one null, as % of rows."""
    rows = []
    for name, df in tables.items():
        for col, share in (df.isna().mean() * 100).items():
            if share > 0:
                rows.append({"table": name, "column": col, "null_pct": round(share, 2)})
    return pd.DataFrame(rows, columns=["table", "column", "null_pct"])


def duplicate_keys(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    rows = []
    for name, key in KEYS.items():
        if key is None:
            continue
        rows.append(
            {
                "table": name,
                "key": "+".join(key),
                "duplicate_rows": int(tables[name].duplicated(key).sum()),
            }
        )
    return pd.DataFrame(rows)


def range_violations(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Counts of values that are implausible but not necessarily schema-invalid."""
    o, i, p = tables["orders"], tables["order_items"], tables["products"]
    checks = {
        "orders: approved_at before purchase_timestamp": (
            o["order_approved_at"] < o["order_purchase_timestamp"]
        ).sum(),
        "orders: delivered_customer_date before approved_at": (
            o["order_delivered_customer_date"] < o["order_approved_at"]
        ).sum(),
        "orders: delivered but missing delivered_customer_date": (
            (o["order_status"] == "delivered") & o["order_delivered_customer_date"].isna()
        ).sum(),
        "orders: non-delivered but has delivered_customer_date": (
            (o["order_status"] != "delivered") & o["order_delivered_customer_date"].notna()
        ).sum(),
        "order_items: price == 0": (i["price"] == 0).sum(),
        "order_items: freight == 0": (i["freight_value"] == 0).sum(),
        "products: weight_g == 0": (p["product_weight_g"] == 0).sum(),
    }
    return pd.DataFrame([{"check": k, "count": int(v)} for k, v in checks.items()])


def geolocation_outliers(geo: pd.DataFrame) -> dict[str, int]:
    """Points outside Brazil's bounding box (config) and prefix coverage stats."""
    g = load_config()["geo"]
    out = ~(
        geo["geolocation_lat"].between(g["lat_min"], g["lat_max"])
        & geo["geolocation_lng"].between(g["lng_min"], g["lng_max"])
    )
    return {
        "geolocation rows": len(geo),
        "outside Brazil bounding box": int(out.sum()),
        "distinct zip prefixes": int(geo["geolocation_zip_code_prefix"].nunique()),
        "exact duplicate rows": int(geo.duplicated().sum()),
    }


def prefix_coverage(tables: dict[str, pd.DataFrame]) -> dict[str, int]:
    """How many customer/seller zip prefixes have no geolocation entry."""
    geo = set(tables["geolocation"]["geolocation_zip_code_prefix"])
    cust = tables["customers"]["customer_zip_code_prefix"]
    sell = tables["sellers"]["seller_zip_code_prefix"]
    return {
        "customer rows with prefix missing from geolocation": int((~cust.isin(geo)).sum()),
        "seller rows with prefix missing from geolocation": int((~sell.isin(geo)).sum()),
    }


def _md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False) if len(df) else "_none_"


def render_report(tables: dict[str, pd.DataFrame], validation: dict[str, str]) -> str:
    geo = geolocation_outliers(tables["geolocation"])
    cov = prefix_coverage(tables)
    kv = lambda d: "\n".join(f"- {k}: **{v:,}**" for k, v in d.items())  # noqa: E731
    val = pd.DataFrame([{"table": k, "pandera": v} for k, v in validation.items()])
    return "\n".join(
        [
            SECTION_START,
            "## Raw data quality (generated by `ontime.data.quality`)",
            "",
            "### Row counts",
            _md(row_counts(tables)),
            "",
            "### Schema validation",
            _md(val),
            "",
            "### Null percentages (columns with any nulls)",
            _md(null_percentages(tables)),
            "",
            "### Duplicate keys",
            _md(duplicate_keys(tables)),
            "",
            "### Out-of-range / inconsistent values",
            _md(range_violations(tables)),
            "",
            "### Geolocation",
            kv(geo),
            kv(cov),
            SECTION_END,
            "",
        ]
    )


def write_report(tables: dict[str, pd.DataFrame], validation: dict[str, str]) -> str:
    """Write/replace the raw-quality section of reports/data_quality.md."""
    path = project_path(load_config()["paths"]["reports_dir"]) / "data_quality.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    section = render_report(tables, validation)
    existing = path.read_text(encoding="utf-8") if path.exists() else "# Data quality report\n\n"
    if SECTION_START in existing and SECTION_END in existing:
        head = existing.split(SECTION_START)[0]
        tail = existing.split(SECTION_END, 1)[1]
        text = head + section + tail.lstrip("\n")
    else:
        text = existing.rstrip("\n") + "\n\n" + section
    path.write_text(text, encoding="utf-8")
    log.info("Wrote %s", path)
    return str(path)
