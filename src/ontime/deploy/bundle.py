"""Build a self-contained deploy bundle (e.g. for Streamlit Community Cloud) on a `deploy` branch.

`main` stays free of data and models (they are git-ignored; the dataset is CC BY-NC-SA). The deploy
branch is built from a clean temporary repository: app + src + configs + the few generated
artifacts the app reads (about 20 MB) + a minimal requirements.txt. The bundle contains DERIVED,
anonymised order-level data: publish it only in line with the dataset licence (non-commercial,
attribution, share-alike).
"""

from __future__ import annotations

import logging
import shutil
import subprocess
import tempfile
from importlib import metadata
from pathlib import Path

from ontime.config import PROJECT_ROOT

log = logging.getLogger(__name__)

COPY_TREES = ["src", "app", "configs", ".streamlit"]
ARTIFACT_FILES = [
    "data/processed/features.parquet",
    "models/logreg.joblib",
    "models/lightgbm.joblib",
    "models/ebm.joblib",
    "reports/results.json",
    "reports/validation_results.json",
    "reports/impact.json",
    "reports/explain_summary.json",
    "reports/stage2_results.json",
    "reports/test_reason_codes.parquet",
    "reports/test_scores.parquet",
    "reports/slices.csv",
    "reports/drift_psi.csv",
    "reports/drift_status.csv",
    "reports/drift_performance.csv",
    "reports/drift_summary.json",
    "reports/figures/explain_ebm_shapes.png",
    "reports/figures/explain_shap_beeswarm.png",
]
RUNTIME_PACKAGES = [
    "streamlit", "plotly", "pandas", "numpy", "scipy", "pyarrow", "scikit-learn", "lightgbm",
    "interpret", "shap", "joblib", "PyYAML", "holidays", "tabulate",
]  # fmt: skip


def requirements_text() -> str:
    """Runtime-only requirements pinned to the versions this project was built with."""
    lines = []
    for name in RUNTIME_PACKAGES:
        try:
            lines.append(f"{name}=={metadata.version(name)}")
        except metadata.PackageNotFoundError:
            lines.append(name)
    return "\n".join(lines) + "\n"


def collect_files() -> tuple[list[Path], list[str]]:
    present = [PROJECT_ROOT / f for f in ARTIFACT_FILES if (PROJECT_ROOT / f).exists()]
    missing = [f for f in ARTIFACT_FILES if not (PROJECT_ROOT / f).exists()]
    return present, missing


def build_bundle(dest: Path) -> dict:
    """Copy sources + artifacts into `dest` (created fresh)."""
    present, missing = collect_files()
    if missing:
        raise FileNotFoundError(f"cannot bundle, missing artifacts: {missing} (run `make all`)")
    for tree in COPY_TREES:
        shutil.copytree(
            PROJECT_ROOT / tree,
            dest / tree,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
        )
    for f in present:
        target = dest / f.relative_to(PROJECT_ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, target)
    (dest / "requirements.txt").write_text(requirements_text(), encoding="utf-8", newline="\n")
    (dest / "README.md").write_text(
        "# OnTime - deploy bundle\n\nGenerated by `make bundle` from the `main` branch. "
        "Entry point: `app/Home.py`. Python 3.11. Contains derived, anonymised data from the Olist "
        "dataset (CC BY-NC-SA 4.0): non-commercial use, attribution, share-alike.\n",
        encoding="utf-8",
        newline="\n",
    )
    size = sum(p.stat().st_size for p in dest.rglob("*") if p.is_file())
    return {
        "files": sum(1 for p in dest.rglob("*") if p.is_file()),
        "megabytes": round(size / 1e6, 1),
    }


def _git(cwd: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout


def publish_deploy_branch(push: bool = True, branch: str = "deploy") -> dict:
    """Build the bundle in a temp repo and force-push it as `branch` (history of that branch is
    disposable by design). Does not touch the working tree or `main`."""
    remote = _git(PROJECT_ROOT, "remote", "get-url", "origin").strip()
    head = _git(PROJECT_ROOT, "rev-parse", "--short", "HEAD").strip()
    with tempfile.TemporaryDirectory(prefix="ontime_bundle_") as tmp:
        dest = Path(tmp)
        info = build_bundle(dest)
        _git(dest, "init", "-q", "-b", branch)
        _git(dest, "add", "-A")
        _git(
            dest, "-c", "user.name=OnTime bundle", "-c", "user.email=bundle@ontime.local",
            "commit", "-q", "-m", f"Deploy bundle built from main@{head}",
        )  # fmt: skip
        if push:
            _git(dest, "push", "-q", "--force", remote, f"{branch}:{branch}")
        log.info("bundle | %s files, %s MB, pushed=%s", info["files"], info["megabytes"], push)
    return {**info, "branch": branch, "pushed": push, "from_commit": head}
