"""Render reports/results.md from results.json. Every number comes from the dict - nothing typed.

Prose is limited to definitions and structure; interpretive sentences are built from the values
(e.g. whether a CI excludes zero) so they cannot drift from the data.
"""

from __future__ import annotations

from ontime.evaluation.plots import LABELS

MODEL_ROWS = ["logreg", "random_forest", "lightgbm", "ebm"]


def _ci(v: list[float], pct: bool = False, nd: int = 3) -> str:
    f = (lambda x: f"{x:.1%}") if pct else (lambda x: f"{x:.{nd}f}")
    return f"[{f(v[0])}, {f(v[1])}]"


def _metric_row(name: str, e: dict) -> str:
    m = e["metrics"]
    k10 = next(t for t in e["top_k"] if abs(t["k"] - 0.10) < 1e-9)
    return (
        f"| {LABELS.get(name, name)} | {m['pr_auc']['value']:.3f} {_ci(m['pr_auc']['ci95'])} "
        f"| {m['roc_auc']['value']:.3f} | {m['brier']['value']:.4f} | {m['log_loss']['value']:.3f} "
        f"| {k10['precision']:.1%} | {k10['recall']:.1%} | {k10['lift']:.2f} {_ci(k10['ci95']['lift'], nd=2)} |"
    )


def _gap_sentence(label: str, d: dict) -> str:
    lo, hi = d["ci95"]
    verdict = (
        "the interval excludes zero (a real difference)"
        if lo > 0 or hi < 0
        else "the interval includes zero (no reliable difference)"
    )
    return f"- **{label}**: {d['diff']:+.3f} PR-AUC, 95% CI {_ci(d['ci95'])} - {verdict}."


def render_results_md(r: dict) -> str:
    pop, prim = r["population"], r["primary_model"]
    where = (
        "TEST set (opened once)" if not r["dry_run"] else "VALIDATION set (dry run - not a result)"
    )
    L: list[str] = []
    a = L.append
    a(f"# OnTime - results on the {where}")
    a("")
    a(
        "_Generated by `ontime.evaluation.run` from `results.json`; no number in this file is typed by hand._"
    )
    a("")
    a("## 1. Evaluation population")
    a(
        f"- Orders approved {pop['from']} to {pop['to']}: **{pop['orders']:,}** orders, "
        f"**{pop['late_orders']:,}** late (**{pop['late_rate']:.1%}**)."
    )
    a(
        f"- Training-period late rate was {pop['train_late_rate']:.1%}: expect probability levels to "
        "be off when the base rate has moved (see section 4)."
    )
    a(f"- Primary model: **{LABELS[prim]}**. {r['primary_selection_rule']}")
    a("")
    a("## 2. Model comparison")
    a(
        "Probabilities are the deployed (validation-calibrated) ones. CIs are 95% percentile bootstrap "
        "(orders resampled; lift@10% resamples whole days)."
    )
    a("")
    a(
        "| model | PR-AUC [95% CI] | ROC-AUC | Brier | log loss | precision@10% | recall@10% | lift@10% [95% CI] |"
    )
    a("|---|---|---|---|---|---|---|---|")
    for b in ("prior_rate", "rule"):
        a(_metric_row(b, r["baselines"][b]))
    for m in MODEL_ROWS:
        a(_metric_row(m, r["models"][m]))
    a("")
    a(
        f"Random-ranking PR-AUC equals the base rate ({pop['late_rate']:.3f}). "
        f"Rule baseline: {r['baselines']['rule']['description']}."
    )
    a("")
    a(
        "![Precision-recall curves](figures/{}_pr_curves.png)".format(
            "dryrun" if r["dry_run"] else "test"
        )
    )
    a("")
    a("![Gains and lift](figures/{}_gains_lift.png)".format("dryrun" if r["dry_run"] else "test"))
    a("")
    a("### Precision / recall at ops capacity")
    a("| model | k | precision | recall | lift | precision 95% CI |")
    a("|---|---|---|---|---|---|")
    for m in MODEL_ROWS:
        for t in r["models"][m]["top_k"]:
            a(
                f"| {LABELS[m]} | {t['k']:.0%} | {t['precision']:.1%} | {t['recall']:.1%} | "
                f"{t['lift']:.2f} | {_ci(t['ci95']['precision'], pct=True)} |"
            )
    a("")
    a("## 3. Glass-box vs black-box (paired bootstrap on PR-AUC)")
    pd_ = r["paired_pr_auc_diff"]
    a(_gap_sentence("EBM minus LightGBM", pd_["ebm_minus_lightgbm"]))
    a(_gap_sentence("Logistic regression minus LightGBM", pd_["logreg_minus_lightgbm"]))
    a(_gap_sentence("EBM minus logistic regression", pd_["ebm_minus_logreg"]))
    a(_gap_sentence(f"{LABELS[prim]} minus hand-written rule", pd_[f"{prim}_minus_rule"]))
    a("")
    a("## 4. Calibration")
    a(
        "Deployed = calibrator fitted once on validation. Rolling = sigmoid refitted each month on "
        "orders delivered in the previous 60 days (only outcomes known before the month began)."
    )
    a("")
    a("| model | calibrator | Brier deployed | Brier rolling | ECE deployed | ECE rolling |")
    a("|---|---|---|---|---|---|")
    for m in MODEL_ROWS:
        e = r["models"][m]
        a(
            f"| {LABELS[m]} | {e['calibrator']} | {e['metrics']['brier']['value']:.4f} | "
            f"{e['rolling_recalibration']['brier']:.4f} | {e['ece_deployed']:.4f} | "
            f"{e['rolling_recalibration']['ece']:.4f} |"
        )
    a("")
    a(
        f"Reference: a constant prediction at the true evaluation-set rate has Brier "
        f"{r['constant_oracle_brier']:.4f}; the training-rate prior scores "
        f"{r['baselines']['prior_rate']['metrics']['brier']['value']:.4f}."
    )
    a("")
    a("![Calibration](figures/{}_calibration.png)".format("dryrun" if r["dry_run"] else "test"))
    a("")
    a("## 5. Month-by-month stability")
    a(
        "| month | model | orders | late rate | PR-AUC | ROC-AUC | lift@10% | mean predicted (deployed) |"
    )
    a("|---|---|---|---|---|---|---|---|")
    for row in r["monthly"]:
        if row["model"] in MODEL_ROWS:
            a(
                f"| {row['month']} | {LABELS[row['model']]} | {row['orders']:,} | {row['late_rate']:.1%} | "
                f"{row['pr_auc']:.3f} | {row['roc_auc']:.3f} | {row['lift_at_10']:.2f} | "
                f"{row['mean_predicted_deployed']:.1%} |"
            )
    a("")
    a(
        "![Monthly PR-AUC](figures/{}_monthly_pr_auc.png)".format(
            "dryrun" if r["dry_run"] else "test"
        )
    )
    a("")
    a("## 6. Where the primary model is weak (slices)")
    a(
        f"Full table for every model: `{r['slices_file']}`. Flagged = ROC-AUC more than 0.05 below "
        "the model's overall ROC-AUC, among slices with enough late orders to measure."
    )
    a("")
    weak = r["slices_primary_weak"]
    if weak:
        a("| slice | value | orders | late rate | ROC-AUC | overall ROC-AUC |")
        a("|---|---|---|---|---|---|")
        for w in weak:
            a(
                f"| {w['slice']} | {w['value']} | {w['orders']:,} | {w['late_rate']:.1%} | "
                f"{w['roc_auc']:.3f} | {w['overall_roc_auc']:.3f} |"
            )
    else:
        a("No measurable slice was flagged for the primary model.")
    a("")
    a("## 7. Policy simulation: what is acting on the top-k% worth?")
    a(
        "**This is a simulation with stated assumptions.** An intervention prevents a would-be-late "
        "order from being late with probability p (not observable in this data; swept below). "
        "Capacity k applies per day. 'Random' is the analytic expectation of picking orders blindly; "
        "'Perfect ranking' is the capacity-limited upper bound."
    )
    a("")
    pol = [x for x in r["policy"] if x["strategy"] in (prim, "rule", "random", "oracle")]
    a(
        "| capacity k | success p | strategy | late orders prevented (expected) | % of all late | gain over random [95% CI] |"
    )
    a("|---|---|---|---|---|---|")
    for x in sorted(pol, key=lambda z: (z["k"], z["p"], z["strategy"])):
        a(
            f"| {x['k']:.0%} | {x['p']:.0%} | {LABELS.get(x['strategy'], x['strategy'])} | "
            f"{x['prevented_expected']:.0f} | {x['prevented_share_of_late']:.1%} | "
            f"{x['extra_vs_random']:+.0f} [{x['extra_vs_random_ci_low']:+.0f}, {x['extra_vs_random_ci_high']:+.0f}] |"
        )
    a("")
    a("![Policy curves](figures/{}_policy_curves.png)".format("dryrun" if r["dry_run"] else "test"))
    a("")
    if "star_gap_assumptions" in r:
        s = r["star_gap_assumptions"]
        a(
            f"Illustrative translation to customer experience: each prevented late order is worth about "
            f"{s['conservative_gap_stars']:.2f} review stars (conservative, reviews after delivery) to "
            f"{s['full_adjusted_gap_stars']:.2f} (full adjusted gap). {s['note']}"
        )
        a("")
    a("## 8. Error analysis")
    a(
        "Top-20 false positives and top-20 false negatives per model: "
        + ", ".join(f"`{f}`" for f in r["error_analysis_files"])
        + "."
    )
    a("")
    a("## 9. Caveats")
    a(
        "- Distribution shift: the late rate differs between training, validation and this period; "
        "deployed probabilities are only as good as the period they were fitted on (section 4)."
    )
    a("- The policy section is a simulation; the success probability p is an assumption.")
    a("- Review-star translation is an association (Phase 3), not a causal effect.")
    a("- Models were fitted on the training period only; none was refit on validation data.")
    return "\n".join(L) + "\n"
