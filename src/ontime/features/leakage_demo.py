"""Measured demonstration of WHY the history rule matters (for interview talking points).

Compares the leak-safe seller late rate with two deliberately leaky variants, by univariate AUC
against the target. Leaky variants are for this report only - they are never features.

* safe              : outcomes known before t0 (delivered < t0)       <- what we use
* leaky_approved    : past orders approved < t0, whatever their outcome (the "obvious" bug:
                      those orders may still be in transit, so their lateness is future info)
* leaky_whole_data  : the seller's late rate over ALL orders except itself (peeks into the future)
"""

from __future__ import annotations

import logging

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from ontime.config import load_config, project_path
from ontime.features.history import past_counts, shrunk_rate

log = logging.getLogger(__name__)


def leak_comparison(orders: pd.DataFrame, features: pd.DataFrame, alpha: float) -> pd.DataFrame:
    """Univariate AUC (train and validation) of safe vs leaky seller late-rate variants."""
    t0 = orders["order_approved_at"].reset_index(drop=True)
    seller = orders["primary_seller_id"].reset_index(drop=True)
    late = orders["is_late"].to_numpy()
    prior = float(np.nanmean(late))  # constant prior is fine for a demonstration

    n, nl = past_counts(seller, t0, late, seller, t0)  # events keyed by APPROVAL time
    leaky_approved = shrunk_rate(nl, n, np.full(len(t0), prior), alpha)

    g = pd.DataFrame({"s": seller, "late": late})
    tot, cnt = g.groupby("s")["late"].transform("sum"), g.groupby("s")["late"].transform("size")
    leaky_whole = ((tot - g["late"]) + alpha * prior) / ((cnt - 1) + alpha)  # exclude self

    variants = {
        "safe (delivered before t0)": features["seller_late_rate_shrunk"].to_numpy(),
        "leaky: approved before t0, outcome ignored": leaky_approved,
        "leaky: whole dataset excluding self": leaky_whole.to_numpy(),
    }
    split = features["split"].reset_index(drop=True)
    rows = []
    for name, x in variants.items():
        row = {"variant": name}
        for s in ["train", "validation", "test"]:
            m = (split == s).to_numpy()
            xs = pd.Series(x[m]).fillna(np.nanmedian(x[m]))
            row[f"auc_{s}"] = roc_auc_score(late[m], xs)
        rows.append(row)
    return pd.DataFrame(rows)


def write_leakage_demo(orders: pd.DataFrame, features: pd.DataFrame) -> None:
    cfg = load_config()
    tbl = leak_comparison(orders, features, cfg["features"]["shrinkage_alpha"])
    path = project_path(cfg["paths"]["reports_dir"]) / "leakage_demo.md"
    path.write_text(
        "\n".join(
            [
                "# Leakage demonstration (generated by `ontime.features.leakage_demo`)",
                "",
                "Univariate ROC-AUC of three versions of the seller late-rate feature against "
                "`is_late`. Only the first is used by the model. A leaky version looks "
                "'better' because it secretly sees outcomes the system could not have known - "
                "the gap is the size of the lie.",
                "",
                tbl.round(4).to_markdown(index=False),
                "",
            ]
        ),
        encoding="utf-8",
    )
    log.info("Wrote %s", path)
